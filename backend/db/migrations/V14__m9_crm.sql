CREATE TABLE CRM_RESERVATIONS (
  ID               VARCHAR2(36)             NOT NULL,
  TENANT_ID        VARCHAR2(36)             NOT NULL,
  BRANCH_ID        VARCHAR2(36)             NOT NULL,
  RESERVATION_NO   NUMBER(12)               NOT NULL,
  CUSTOMER_ID      VARCHAR2(36),
  CUSTOMER_NAME    VARCHAR2(200)            NOT NULL,
  CUSTOMER_PHONE   VARCHAR2(40)             NOT NULL,
  RESERVATION_DATE DATE                     NOT NULL,
  RESERVATION_TIME VARCHAR2(5)              NOT NULL,
  GUEST_COUNT      NUMBER(4)                NOT NULL,
  TABLE_ID         VARCHAR2(36),
  NOTES            CLOB,
  STATUS           VARCHAR2(20) DEFAULT 'pending' NOT NULL,
  CONFIRMED_AT     TIMESTAMP WITH TIME ZONE,
  SEATED_AT        TIMESTAMP WITH TIME ZONE,
  CANCELLED_AT     TIMESTAMP WITH TIME ZONE,
  CANCEL_REASON    VARCHAR2(500),
  CREATED_BY       VARCHAR2(36),
  UPDATED_BY       VARCHAR2(36),
  CREATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  ROW_VERSION      NUMBER(19) DEFAULT 1     NOT NULL,
  CONSTRAINT PK_CRM_RESERVATIONS PRIMARY KEY (ID),
  CONSTRAINT FK_CRM_RESV_TENANT FOREIGN KEY (TENANT_ID) REFERENCES TENANTS (ID),
  CONSTRAINT FK_CRM_RESV_BRANCH FOREIGN KEY (BRANCH_ID) REFERENCES BRANCHES (ID),
  CONSTRAINT FK_CRM_RESV_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CRM_CUSTOMERS (ID) ON DELETE SET NULL,
  CONSTRAINT FK_CRM_RESV_TABLE FOREIGN KEY (TABLE_ID) REFERENCES DINING_TABLES (ID) ON DELETE SET NULL,
  CONSTRAINT UQ_CRM_RESV_NO UNIQUE (TENANT_ID, BRANCH_ID, RESERVATION_NO),
  CONSTRAINT CK_CRM_RESV_STATUS CHECK (STATUS IN ('pending','confirmed','seated','cancelled','no_show')),
  CONSTRAINT CK_CRM_RESV_GUESTS CHECK (GUEST_COUNT > 0),
  CONSTRAINT CK_CRM_RESV_TIME CHECK (REGEXP_LIKE(RESERVATION_TIME, '^[0-2][0-9]:[0-5][0-9]$'))
);
CREATE INDEX IX_CRM_RESV_BRANCH_DATE ON CRM_RESERVATIONS (TENANT_ID, BRANCH_ID, RESERVATION_DATE, STATUS);

