
CREATE SEQUENCE CRM_RESERVATION_NO_SEQ START WITH 1000 INCREMENT BY 1 NOCACHE;

CREATE TABLE CRM_CUSTOMERS (
  ID              VARCHAR2(36)             NOT NULL,
  TENANT_ID       VARCHAR2(36)             NOT NULL,
  PHONE           VARCHAR2(40)             NOT NULL,
  FULL_NAME       VARCHAR2(200),
  EMAIL           VARCHAR2(160),
  BIRTHDAY        DATE,
  NOTES           CLOB,
  PREFERENCES     CLOB,
  LOYALTY_TIER    VARCHAR2(20) DEFAULT 'bronze' NOT NULL,
  LOYALTY_POINTS  NUMBER(12)  DEFAULT 0    NOT NULL,
  TOTAL_SPENT     NUMBER(18,4) DEFAULT 0   NOT NULL,
  VISIT_COUNT     NUMBER(10) DEFAULT 0     NOT NULL,
  SMS_CONSENT     NUMBER(1) DEFAULT 1      NOT NULL,
  EMAIL_CONSENT   NUMBER(1) DEFAULT 1      NOT NULL,
  IS_BLOCKED      NUMBER(1) DEFAULT 0      NOT NULL,
  BLOCK_REASON    VARCHAR2(500),
  CREATED_BY      VARCHAR2(36),
  UPDATED_BY      VARCHAR2(36),
  CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  ROW_VERSION     NUMBER(19) DEFAULT 1     NOT NULL,
  CONSTRAINT PK_CRM_CUSTOMERS PRIMARY KEY (ID),
  CONSTRAINT FK_CRM_CUSTOMERS_TENANT FOREIGN KEY (TENANT_ID) REFERENCES TENANTS (ID),
  CONSTRAINT UQ_CRM_CUSTOMERS_PHONE UNIQUE (TENANT_ID, PHONE),
  CONSTRAINT CK_CRM_CUSTOMERS_TIER CHECK (LOYALTY_TIER IN ('bronze','silver','gold','platinum')),
  CONSTRAINT CK_CRM_CUSTOMERS_SMS CHECK (SMS_CONSENT IN (0,1)),
  CONSTRAINT CK_CRM_CUSTOMERS_EMAIL CHECK (EMAIL_CONSENT IN (0,1)),
  CONSTRAINT CK_CRM_CUSTOMERS_BLOCKED CHECK (IS_BLOCKED IN (0,1)),
  CONSTRAINT CK_CRM_CUSTOMERS_PREFS CHECK (PREFERENCES IS NULL OR PREFERENCES IS JSON)
);
CREATE INDEX IX_CRM_CUSTOMERS_TENANT ON CRM_CUSTOMERS (TENANT_ID, UPDATED_AT DESC);
CREATE INDEX IX_CRM_CUSTOMERS_EMAIL ON CRM_CUSTOMERS (TENANT_ID, EMAIL);

