  CONSTRAINT FK_CRM_DELIVERY_TENANT FOREIGN KEY (TENANT_ID) REFERENCES TENANTS (ID),
  CONSTRAINT FK_CRM_DELIVERY_BRANCH FOREIGN KEY (BRANCH_ID) REFERENCES BRANCHES (ID),
