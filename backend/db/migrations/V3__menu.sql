CREATE TABLE PRICE_LIST_ITEMS (
  ID            VARCHAR2(36)   NOT NULL,
  PRICE_LIST_ID VARCHAR2(36)   NOT NULL,
  MENU_ITEM_ID  VARCHAR2(36)   NOT NULL,
  PRICE         NUMBER(18,4)   NOT NULL,
  CONSTRAINT PK_PRICE_LIST_ITEMS PRIMARY KEY (ID),
  CONSTRAINT FK_PLI_LIST FOREIGN KEY (PRICE_LIST_ID) REFERENCES PRICE_LISTS (ID) ON DELETE CASCADE,
  CONSTRAINT FK_PLI_ITEM FOREIGN KEY (MENU_ITEM_ID)  REFERENCES MENU_ITEMS (ID) ON DELETE CASCADE,
  CONSTRAINT UQ_PLI UNIQUE (PRICE_LIST_ID, MENU_ITEM_ID),
  CONSTRAINT CK_PLI_PRICE CHECK (PRICE >= 0)
);

CREATE TABLE COMBOS (
  ID          VARCHAR2(36)             NOT NULL,
  TENANT_ID   VARCHAR2(36)             NOT NULL,
  NAME        VARCHAR2(200)            NOT NULL,
  PRICE       NUMBER(18,4) DEFAULT 0   NOT NULL,
  IS_ACTIVE   NUMBER(1)  DEFAULT 1     NOT NULL,
  CREATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_BY  VARCHAR2(36),
  UPDATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_BY  VARCHAR2(36),
  ROW_VERSION NUMBER(19) DEFAULT 1     NOT NULL,
  CONSTRAINT PK_COMBOS PRIMARY KEY (ID),
  CONSTRAINT FK_COMBO_TENANT FOREIGN KEY (TENANT_ID) REFERENCES TENANTS (ID),
  CONSTRAINT CK_COMBO_ACTIVE CHECK (IS_ACTIVE IN (0,1))
);

CREATE TABLE COMBO_ITEMS (
  ID           VARCHAR2(36) NOT NULL,
  COMBO_ID     VARCHAR2(36) NOT NULL,
  MENU_ITEM_ID VARCHAR2(36) NOT NULL,
  QUANTITY     NUMBER(6) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_COMBO_ITEMS PRIMARY KEY (ID),
  CONSTRAINT FK_COMBOITEM_COMBO FOREIGN KEY (COMBO_ID)     REFERENCES COMBOS (ID) ON DELETE CASCADE,
  CONSTRAINT FK_COMBOITEM_ITEM  FOREIGN KEY (MENU_ITEM_ID) REFERENCES MENU_ITEMS (ID),
  CONSTRAINT CK_COMBOITEM_QTY CHECK (QUANTITY > 0)
);

CREATE TABLE ITEM_BARCODES (
  ID           VARCHAR2(36) NOT NULL,
  TENANT_ID    VARCHAR2(36) NOT NULL,
  MENU_ITEM_ID VARCHAR2(36) NOT NULL,
  BARCODE      VARCHAR2(64) NOT NULL,
  CONSTRAINT PK_ITEM_BARCODES PRIMARY KEY (ID),
  CONSTRAINT FK_BARCODE_ITEM FOREIGN KEY (MENU_ITEM_ID) REFERENCES MENU_ITEMS (ID) ON DELETE CASCADE,
  CONSTRAINT UQ_BARCODE UNIQUE (TENANT_ID, BARCODE)
);
