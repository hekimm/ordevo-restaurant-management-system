
CREATE TABLE MENU_CATEGORIES (
  ID          VARCHAR2(36)             NOT NULL,
  TENANT_ID   VARCHAR2(36)             NOT NULL,
  BRANCH_ID   VARCHAR2(36),
  NAME        VARCHAR2(150)            NOT NULL,
  COLOR       VARCHAR2(16),
  SORT_ORDER  NUMBER(6)  DEFAULT 0     NOT NULL,
  IS_ACTIVE   NUMBER(1)  DEFAULT 1     NOT NULL,
  CREATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_BY  VARCHAR2(36),
  UPDATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_BY  VARCHAR2(36),
  ROW_VERSION NUMBER(19) DEFAULT 1     NOT NULL,
  CONSTRAINT PK_MENU_CATEGORIES PRIMARY KEY (ID),
  CONSTRAINT FK_MENUCAT_TENANT FOREIGN KEY (TENANT_ID) REFERENCES TENANTS (ID),
  CONSTRAINT UQ_MENUCAT_NAME UNIQUE (TENANT_ID, NAME),
  CONSTRAINT CK_MENUCAT_ACTIVE CHECK (IS_ACTIVE IN (0,1))
);
CREATE INDEX IX_MENUCAT_TENANT ON MENU_CATEGORIES (TENANT_ID);

CREATE TABLE MENU_ITEMS (
  ID           VARCHAR2(36)             NOT NULL,
  TENANT_ID    VARCHAR2(36)             NOT NULL,
  CATEGORY_ID  VARCHAR2(36)             NOT NULL,
  NAME         VARCHAR2(200)            NOT NULL,
  DESCRIPTION  VARCHAR2(1000),
  PRICE        NUMBER(18,4) DEFAULT 0   NOT NULL,
  VAT_RATE     NUMBER(5,2)  DEFAULT 10  NOT NULL,
  SKU          VARCHAR2(60),
  IMAGE_URL    VARCHAR2(500),
  PREP_STATION VARCHAR2(40),
  SORT_ORDER   NUMBER(6)  DEFAULT 0     NOT NULL,
  IS_ACTIVE    NUMBER(1)  DEFAULT 1     NOT NULL,
  CREATED_AT   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_BY   VARCHAR2(36),
  UPDATED_AT   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_BY   VARCHAR2(36),
  ROW_VERSION  NUMBER(19) DEFAULT 1     NOT NULL,
  CONSTRAINT PK_MENU_ITEMS PRIMARY KEY (ID),
  CONSTRAINT FK_MENUITEM_TENANT FOREIGN KEY (TENANT_ID) REFERENCES TENANTS (ID),
  CONSTRAINT FK_MENUITEM_CAT FOREIGN KEY (CATEGORY_ID) REFERENCES MENU_CATEGORIES (ID),
  CONSTRAINT CK_MENUITEM_ACTIVE CHECK (IS_ACTIVE IN (0,1)),
  CONSTRAINT CK_MENUITEM_PRICE CHECK (PRICE >= 0)
);
CREATE INDEX IX_MENUITEM_TENANT ON MENU_ITEMS (TENANT_ID);
CREATE INDEX IX_MENUITEM_CAT ON MENU_ITEMS (CATEGORY_ID);

CREATE TABLE MODIFIER_GROUPS (
  ID          VARCHAR2(36)             NOT NULL,
  TENANT_ID   VARCHAR2(36)             NOT NULL,
  NAME        VARCHAR2(150)            NOT NULL,
  MIN_SELECT  NUMBER(4)  DEFAULT 0     NOT NULL,
  MAX_SELECT  NUMBER(4)  DEFAULT 1     NOT NULL,
  IS_REQUIRED NUMBER(1)  DEFAULT 0     NOT NULL,
  CREATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_BY  VARCHAR2(36),
  UPDATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_BY  VARCHAR2(36),
  ROW_VERSION NUMBER(19) DEFAULT 1     NOT NULL,
  CONSTRAINT PK_MODIFIER_GROUPS PRIMARY KEY (ID),
  CONSTRAINT FK_MODGRP_TENANT FOREIGN KEY (TENANT_ID) REFERENCES TENANTS (ID),
  CONSTRAINT UQ_MODGRP_NAME UNIQUE (TENANT_ID, NAME),
  CONSTRAINT CK_MODGRP_REQ CHECK (IS_REQUIRED IN (0,1))
);

CREATE TABLE MODIFIERS (
  ID          VARCHAR2(36)             NOT NULL,
  TENANT_ID   VARCHAR2(36)             NOT NULL,
  GROUP_ID    VARCHAR2(36)             NOT NULL,
  NAME        VARCHAR2(150)            NOT NULL,
  PRICE_DELTA NUMBER(18,4) DEFAULT 0   NOT NULL,
  SORT_ORDER  NUMBER(6)  DEFAULT 0     NOT NULL,
  IS_ACTIVE   NUMBER(1)  DEFAULT 1     NOT NULL,
  CREATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_BY  VARCHAR2(36),
  UPDATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_BY  VARCHAR2(36),
  ROW_VERSION NUMBER(19) DEFAULT 1     NOT NULL,
  CONSTRAINT PK_MODIFIERS PRIMARY KEY (ID),
  CONSTRAINT FK_MOD_GROUP FOREIGN KEY (GROUP_ID) REFERENCES MODIFIER_GROUPS (ID) ON DELETE CASCADE,
  CONSTRAINT CK_MOD_ACTIVE CHECK (IS_ACTIVE IN (0,1))
);
CREATE INDEX IX_MOD_GROUP ON MODIFIERS (GROUP_ID);

CREATE TABLE ITEM_MODIFIER_GROUPS (
  ITEM_ID    VARCHAR2(36) NOT NULL,
  GROUP_ID   VARCHAR2(36) NOT NULL,
  SORT_ORDER NUMBER(6) DEFAULT 0 NOT NULL,
  CONSTRAINT PK_ITEM_MODGRP PRIMARY KEY (ITEM_ID, GROUP_ID),
  CONSTRAINT FK_IMG_ITEM  FOREIGN KEY (ITEM_ID)  REFERENCES MENU_ITEMS (ID) ON DELETE CASCADE,
  CONSTRAINT FK_IMG_GROUP FOREIGN KEY (GROUP_ID) REFERENCES MODIFIER_GROUPS (ID) ON DELETE CASCADE
);

CREATE TABLE PRICE_LISTS (
